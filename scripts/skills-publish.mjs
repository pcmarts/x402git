#!/usr/bin/env node
/**
 * scripts/skills-publish.mjs — publish the two agent skills to the public GitHub repo.
 *
 *   npm run skills:publish                   # push if anything changed
 *   npm run skills:publish -- --check        # report drift, change nothing
 *   npm run skills:publish -- --tag v1.1.0   # sync, then tag the mirror and cut a GitHub release
 *
 * The skills are served from this app at /.well-known/agent-skills/<name>/SKILL.md, with
 * a sha256 digest in the index (docs/agent-discovery.md). skills.sh and `npx skills add`
 * read a public GitHub repo instead, so the same bytes are mirrored to
 * github.com/pcmarts/x402git-skills in the layout the skills CLI discovers:
 * `skills/<name>/SKILL.md`. Published from lib/skills/*.md — the one source — so the
 * digest an agent verifies against the index is the digest of what GitHub serves.
 *
 * The skills are MIT; the app is AGPL-3.0-only. The mirror's MIT LICENSE is written by
 * this script like everything else there. `--tag vX.Y.Z` cuts a release of the mirror, so
 * a release of the skills repo is reproducible from one command.
 *
 * Needs `gh` authenticated with push rights to the repo. Never edits the mirror by hand.
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const REPO = "pcmarts/x402git-skills";
const SITE = "https://x402git.com";
const LICENCE_YEAR = 2026; // year of first publication; do not bump
const check = process.argv.includes("--check");
const tag = tagArg(process.argv);

const srcDir = join(process.cwd(), "lib", "skills");
const skills = readdirSync(srcDir)
  .filter((f) => f.endsWith(".md"))
  .map((f) => ({ name: f.replace(/\.md$/, ""), bytes: readFileSync(join(srcDir, f)) }));
if (skills.length === 0) throw new Error("no skills in lib/skills");

const readme = `# X402 Git — agent skills

Two skills for agents that buy or sell private git repositories on [X402 Git](${SITE}):
paid access over [x402](https://x402.org) (USDC on Base), with the manifest public and
the contents private until paid for.

\`\`\`
npx skills add ${REPO}
\`\`\`

| Skill | What it is for |
| --- | --- |
${skills.map((s) => `| [\`${s.name}\`](skills/${s.name}/SKILL.md) | ${description(s.bytes)} |`).join("\n")}

These files are mirrored, byte for byte, from the ones the site serves at
\`${SITE}/.well-known/agent-skills/<name>/SKILL.md\`; the index at
\`${SITE}/.well-known/agent-skills/index.json\` carries a sha256 digest of each. The
same tools are an MCP server at \`${SITE}/api/mcp\`
(\`claude mcp add --transport http x402git ${SITE}/api/mcp\`).

Edits go to the site, not here: this repository is regenerated by its publisher.
Licence: MIT ([LICENSE](LICENSE)). Use of the service itself is under ${SITE}/terms.md.
`;

const licence = `MIT License

Copyright (c) ${LICENCE_YEAR} X402 Git

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.
`;

const work = join(tmpdir(), `x402git-skills-${process.pid}`);
rmSync(work, { recursive: true, force: true });
execFileSync("gh", ["repo", "clone", REPO, work, "--", "--quiet", "--depth", "1"], { stdio: "inherit" });

const wanted = new Map([
  ["README.md", Buffer.from(readme)],
  ["LICENSE", Buffer.from(licence)],
]);
for (const s of skills) wanted.set(join("skills", s.name, "SKILL.md"), s.bytes);

let changed = 0;
for (const [rel, bytes] of wanted) {
  const target = join(work, rel);
  const same = existsSync(target) && readFileSync(target).equals(bytes);
  if (same) continue;
  changed++;
  console.log(`${existsSync(target) ? "update" : "add"}    ${rel}`);
  if (!check) {
    mkdirSync(join(target, ".."), { recursive: true });
    writeFileSync(target, bytes);
  }
}

const git = (...args) => execFileSync("git", ["-C", work, ...args], { stdio: "inherit" });
const today = new Date().toISOString().slice(0, 10);

if (changed === 0) {
  console.log("mirror is current");
} else if (check) {
  console.log(`${changed} file(s) differ; run without --check to publish`);
  process.exitCode = 2;
} else {
  git("add", "-A");
  git("commit", "-q", "-m", `sync from x402git.com (${today})`);
  git("push", "-q");
  console.log(`published ${changed} file(s) to github.com/${REPO}`);
}

if (tag) {
  // Tag whatever the mirror now holds (the sync commit, or the unchanged head) and cut a
  // GitHub release from it. Refuse to move an existing tag: a release is a fixed point.
  const exists = execFileSync("git", ["-C", work, "ls-remote", "--tags", "origin", `refs/tags/${tag}`]).toString().trim();
  if (exists) throw new Error(`${tag} already exists on ${REPO}; tags are never moved`);
  if (check) {
    console.log(`would tag ${tag} and create its GitHub release`);
  } else {
    const names = skills.map((s) => s.name).join(", ");
    git("tag", "-a", tag, "-m", `x402git-skills ${tag}: ${names} (sync from x402git.com, ${today})`);
    git("push", "-q", "origin", tag);
    execFileSync(
      "gh",
      ["release", "create", tag, "-R", REPO, "--verify-tag", "--title", tag, "--notes",
        `Skills in this release: ${names}.\n\nMirrored byte for byte from ${SITE}/.well-known/agent-skills/ on ${today}; the index there carries each file's sha256. MIT licence.`],
      { stdio: "inherit" },
    );
    console.log(`tagged ${tag} and created its release on github.com/${REPO}`);
  }
}
rmSync(work, { recursive: true, force: true });

function tagArg(argv) {
  const i = argv.indexOf("--tag");
  if (i === -1) return null;
  const v = argv[i + 1];
  if (!v || !/^v\d+\.\d+\.\d+$/.test(v)) throw new Error("--tag wants a version like v1.0.0");
  return v;
}

function description(bytes) {
  const m = /^description:\s*(.+)$/m.exec(bytes.toString("utf8"));
  return m ? m[1].trim() : "";
}
