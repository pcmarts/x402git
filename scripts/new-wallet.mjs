#!/usr/bin/env node
/**
 * scripts/new-wallet.mjs — generate a wallet, write it to a gitignored file.
 *
 *   node scripts/new-wallet.mjs receiving-mainnet --purpose "platform receiving address"
 *
 * Writes `<name>.local.json` (matched by `*.local.json` in .gitignore, like
 * sweep-wallet.local.json) with mode 600, and prints **only the address**. The private
 * key never reaches stdout, so it never reaches terminal scrollback, a screenshot, or
 * anything pasted into an issue.
 *
 * Keys come from viem's `generatePrivateKey`, which is `crypto.getRandomValues` — the
 * platform CSPRNG, not `Math.random`.
 *
 * ## Which wallets should actually live here
 *
 * **The platform receiving address should not.** Nothing in this system signs from it:
 * `PLATFORM_RECEIVING_ADDRESS` is used once, as the `payTo` of a 402, and the deployment
 * only ever needs the address. A key generated on a laptop for an address that will hold
 * every buyer payment is a hot key with no reason to be hot — generate that one in a
 * hardware wallet and paste the address instead. This script will make one if you want
 * it, and then you should import it and delete the file.
 *
 * **The sweep signer has to be hot**, because it signs every payout unattended (§14.8
 * says it belongs in a signing service; V0 keeps it in the deployment env). Keep its
 * balance near what is owed rather than parking the float in it.
 */

import { chmodSync, existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);
const flag = (n) => {
  const i = argv.indexOf(`--${n}`);
  return i > -1 ? argv[i + 1] : null;
};

const name = argv[0];
if (!name || name.startsWith("--")) {
  console.error('usage: new-wallet.mjs <name> --purpose "what it is for"');
  process.exit(1);
}
if (!/^[a-z0-9-]+$/.test(name)) {
  console.error("error: name must be lowercase letters, digits and hyphens");
  process.exit(1);
}

const file = path.join(ROOT, `${name}.local.json`);
if (existsSync(file)) {
  console.error(`error: ${name}.local.json already exists. Refusing to overwrite a key.`);
  process.exit(1);
}

const privateKey = generatePrivateKey();
const { address } = privateKeyToAccount(privateKey);
const purpose = flag("purpose") ?? "unspecified";

writeFileSync(
  file,
  `${JSON.stringify(
    {
      note: `${purpose}. Generated by scripts/new-wallet.mjs. Gitignored via *.local.json. Import this into a wallet you control and delete this file — or, for a signer, move it to the deployment env and delete this file.`,
      purpose,
      address,
      private_key: privateKey,
      created_at: new Date().toISOString(),
    },
    null,
    2,
  )}\n`,
);
chmodSync(file, 0o600);

console.log(`address  ${address}`);
console.log(`written  ${name}.local.json (mode 600, gitignored)`);
console.log("The private key was not printed. It is only in that file.");
