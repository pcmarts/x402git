/**
 * scripts/diagrams-to-tsx.mjs — bake the archify diagrams into the how-it-works page.
 *
 * The diagrams are authored as archify specs in `diagrams/*.json` and delivered as
 * standalone HTML by `archify deliver` (which validates geometry and label clearance).
 * The page does not ship the 700KB viewer: this script lifts the one inline <svg> out
 * of each delivered artifact and writes `app/how-it-works/_diagrams.tsx`, themed by
 * `.protocol` rules in globals.css so the drawings wear the site's own ink set.
 *
 * Per SVG it: prefixes every id (two diagrams share a page and both define #arrowhead),
 * squares every corner (the system has --radius: 0), and replaces archify's generic
 * <desc> with a real description for readers who cannot see the drawing.
 *
 * Re-run after re-delivering a diagram:  node scripts/diagrams-to-tsx.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const DIAGRAMS = [
  {
    slug: "xseq",
    component: "ExchangeDiagram",
    artifact: "diagrams/x402-exchange.html",
    desc:
      "Sequence diagram. The buyer sends GET the repository to X402 Git and receives 402 with the price and a quote id. " +
      "The buyer repeats the GET with a signed USDC authorization. X402 Git screens the payer, re-checks the quote, and asks the facilitator to verify and settle; " +
      "the facilitator submits the transfer to Base with gas sponsored and returns the transaction hash. " +
      "Only then does X402 Git answer 200 with a download URL that lasts five minutes.",
  },
  {
    slug: "split",
    component: "SplitDiagram",
    artifact: "diagrams/payment-split.html",
    desc:
      "Flow diagram. One signed transfer of $9.00 USDC on Base moves from the buyer's wallet to the platform address. " +
      "It splits: $0.90 — the flat 10% fee and the platform's only revenue — and $8.10, your 90%, held seven days, " +
      "then swept automatically to the bound wallet, the only destination. The holdback is also where a takedown refund is paid from, if ever.",
  },
];

const out = [];
out.push(
  "/**",
  " * GENERATED by scripts/diagrams-to-tsx.mjs — do not edit the SVG by hand.",
  " * Source of truth: diagrams/*.json (archify specs); re-deliver, then re-run the script.",
  " * Colour and type come from the `.protocol` rules in app/globals.css.",
  " */",
  "",
);

for (const d of DIAGRAMS) {
  const html = readFileSync(join(root, d.artifact), "utf8");
  const match = html.match(/<svg[\s\S]*?<\/svg>/);
  if (!match) throw new Error(`no <svg> in ${d.artifact}`);
  let svg = match[0];

  // Two diagrams on one page: every id (and reference to one) gets the diagram's slug.
  svg = svg.replace(/id="([^"]+)"/g, `id="${d.slug}-$1"`);
  svg = svg.replace(/url\(#([^)]+)\)/g, `url(#${d.slug}-$1)`);
  svg = svg.replace(/aria-labelledby="([^"]+)"/g, (_, ids) =>
    `aria-labelledby="${ids.split(/\s+/).map((i) => `${d.slug}-${i}`).join(" ")}"`,
  );

  // --radius: 0. Every corner in the system is square, including drawn ones.
  svg = svg.replace(/\s(?:rx|ry)="[^"]*"/g, "");

  // A description a screen reader can use instead of "generated by Archify".
  svg = svg.replace(/<desc id="([^"]+)">[\s\S]*?<\/desc>/, `<desc id="$1">${d.desc}</desc>`);

  if (svg.includes("`") || svg.includes("${")) throw new Error(`unescapable SVG in ${d.artifact}`);

  out.push(
    `const ${d.slug.toUpperCase()}_SVG = \`${svg}\`;`,
    "",
    `export function ${d.component}() {`,
    `  return <div className="protocol-scroll" dangerouslySetInnerHTML={{ __html: ${d.slug.toUpperCase()}_SVG }} />;`,
    "}",
    "",
  );
}

writeFileSync(join(root, "app/how-it-works/_diagrams.tsx"), out.join("\n"));
console.log("wrote app/how-it-works/_diagrams.tsx");
